"""حروف العربية وعلاماتها — مصدرٌ واحد لكل المحاور.

قبل إعادة الهيكلة كانت هذه الثوابت مقيمةً في وحدة المحور الأول، فاضطُرّ
المحور الثالث إلى استيرادها منه. وذلك خلطُ **بيانات** بـ**سلوك**: المحور
الثالث لا يعتمد على منطق التطبيع، وإنما يعرف الأبجدية نفسها.

فصلُها هنا يجعل الاعتماد بين المحاور مقصورًا على **الواجهات** لا على الثوابت.
"""

from __future__ import annotations

import unicodedata

# --- ترتيب العلامات: قاعدةٌ عامّة عند الحدّ ---------------------------------


def canonical_mark_order(text: str) -> str:
    """يرتّب علاماتِ كلِّ حاملٍ ترتيبًا قانونيًّا واحدًا، ولا يغيّر حرفًا.

    **القاعدة العامّة** — بديلُ الدرس المسجَّل لا تكرارُه:

    كان أوّلُ جردٍ للفظ الجلالة كُتب باليد لا يطابق منه إلا سطحٌ واحد من
    ٢٬٧٠٤، لأن النصّ يكتب الشدّة قبل الحركة واليدُ تعكسهما. وقد عولج يومَها
    بنقل الأسطح من مصدرها — وذلك **علاجُ موضع**. وهذه هي القاعدة العامّة:
    يُوحَّد الترتيبُ عند الحدّ مرّةً واحدة، فلا تبقى مقارنةٌ في المحرّك كلِّه
    معتمدةً على ترتيب الطبع.

    والترتيب المعتمد هو ترتيبُ يونيكود القانونيّ (`Canonical Ordering`):
    تُرتَّب علاماتُ الحامل الواحد بصنفها التركيبيّ تصاعديًّا، ترتيبًا
    **مستقرًّا** فلا يتبدّل ما تساوى صنفُه.

        كتابةُ النصّ   لَّ = ل + ٠٦٥١ + ٠٦٤E     (شدّة ثم فتحة)
        كتابةُ اليد    لَّ = ل + ٠٦٤E + ٠٦٥١     (فتحة ثم شدّة)
        بعد التوحيد    كلتاهما = ل + ٠٦٤E + ٠٦٥١

    ولمَ لم تُستعمل `NFC` أو `NFD` وهي تفعل الترتيب نفسه؟ لأنهما تفعلان
    **أكثر** منه: `NFC` تركّب «ا + ٓ» فتصيّرها «آ»، و`NFD` تفكّ «آ» إلى
    «ا + ٓ». وكلاهما تغييرُ حروفٍ لا ترتيبِ علامات، وهو ما يقرّره حكمُ
    المالك في N1 وN10.2 لا خوارزميةُ يونيكود. فأُخذ من الخوارزمية
    خطوةُ الترتيب وحدَها.

    والدالّة **مُتساوية القوّة** (idempotent): تطبيقُها مرّتين كتطبيقِها مرّة.
    """
    out: list[str] = []
    run: list[str] = []
    for ch in text:
        if unicodedata.combining(ch):
            run.append(ch)
            continue
        if run:
            out.extend(sorted(run, key=unicodedata.combining))
            run = []
        out.append(ch)
    if run:
        out.extend(sorted(run, key=unicodedata.combining))
    return "".join(out)


# --- الفواصلُ عند الحدّ: حكمُ المالك، بحرفه لا بتوسيعه -----------------------

#: العلامتان اللتان حكم المالكُ فيهما: «عالج الفاصلة والنقطة».
#:
#: ``\u060C`` الفاصلة العربية · ``\u002E`` النقطة. **وهما فقط.**
OWNER_SEPARATORS: frozenset[str] = frozenset({"\u060C", "\u002E"})

#: علاماتٌ تُسقط توكناتٍ ولم يشملها الحكم — تبقى ساقطةً وتُرفع باسمها.
#: وتُعلَن هنا لتكون الفجوةُ **مرئيّةً في الشيفرة** لا في تقريرٍ وحده.
UNRULED_SEPARATORS: frozenset[str] = frozenset({"\u061F", "\u061B", "\u003A"})


def strip_owner_separators(text: str) -> tuple[str, str]:
    """يقطع فواصلَ المالك من طرفَي التوكن، ويردّ ما قُطع ليُسجَّل.

    **حكمُ المالك**، وهو علّةُ هذه الدالّة كلِّها:

        «عالج الفاصلة والنقطة»

    فالفاصلةُ والنقطةُ **فاصلتان لا حرفان**: لا تدخلان بنيةَ الكلمة، فلا
    تُخرجانها من الجرد. وقبل هذا الحكم كان التوكنُ كلُّه يسقط
    ``IGNORED_NON_WORD_TOKEN`` — ٢٨ توكنًا في المثبَّتات، صفرٌ في المصحف،
    وخُمسُ جملةِ النازلة.

    **وحدُّ الحكم يُحترم حرفًا.** حكمَ في علامتين فيُعمل بهما وحدَهما:
    ``؟`` و``؛`` و``:`` تبقى مُسقِطةً كما كانت، وترتفع إليه باسمها. ومدُّ
    الحكم إلى «كلّ ترقيم» استنباطُ قاعدةٍ لم يقلها — وهو ممنوع.

    **وحدُّ الموضع: الطرفان لا الداخل.** الفاصلُ يفصل، فموضعُه حدُّ التوكن.
    ونقطةٌ بين حرفين ليست فاصلًا بل شيءٌ آخر لم يُحكم فيه، فتبقى مُسقِطة.
    والقطعُ من الطرفين معًا لأنّ الحكمَ في **هوية العلامة** لا في موضعها؛
    والمشهودُ في هذه النصوص كلِّها لاحقٌ لا سابق، وذلك مُعلَنٌ لا مطويّ.

    ولا يُحذف المقطوعُ بلا أثر: يُردّ ليُسجَّل في مخرج المحور صفر، فيُقرأ
    من الجدول ما كان لاصقًا بكلّ كلمة.

        strip_owner_separators("مَعَهُ،")  →  ("مَعَهُ", "،")
        strip_owner_separators("حَضَرْتَ؟") →  ("حَضَرْتَ؟", "")   حكمٌ لم يُصدر
    """
    start, end = 0, len(text)
    while start < end and text[start] in OWNER_SEPARATORS:
        start += 1
    while end > start and text[end - 1] in OWNER_SEPARATORS:
        end -= 1
    return text[start:end], text[:start] + text[end:]


